import assert from "node:assert/strict";
import {seed,assess,lots,tasks} from "../legacy/domain.js";
const state=seed();
let a=assess(state,"SC6820",100000,"2026-09-25");
assert.deepEqual([a.stock,a.expected,a.gap],[20000,50000,30000]);
assert(a.conditions.some(c=>c.includes("昨日快照")));
assert.equal(assess(state,"SC6820",20000,"2026-09-22").gap,20000,"仓库可用不等于今天客户收到");
state.wipUpdated=true;state.ftReply="accepted";
a=assess(state,"SC6820",100000,"2026-09-25");
assert(a.conditions.some(c=>c.includes("最终良品")));
assert.equal(lots(state).find(l=>l.id==="FT-0920").stage,"待终测","接受不等于开测");
state.priority="requested";assert.equal(assess(state,"SC6820",100000,"2026-09-25").gap,30000);
state.priority="accepted";state.assemblyReply="accepted";
assert.equal(assess(state,"SC6820",100000,"2026-09-25").gap,0);
assert.equal(assess(state,"SC6820",100000,"2026-09-25").status,"conditional");
assert.equal(lots(state).find(l=>l.id==="AS-0919").eta,"2026-09-28");
state.afternoon=true;
assert.equal(tasks(state).find(t=>t.id==="ft").status,"waiting");
assert.equal(tasks(state).find(t=>t.id==="priority").status,"waiting");
state.ftReconfirmed=true;state.assemblyReconfirmed=true;
assert.equal(tasks(state).find(t=>t.id==="ft").status,"done");
state.priority="rejected";state.assemblyReply="rejected";
assert.equal(assess(state,"SC6820",100000,"2026-09-25").gap,30000);
assert.equal(lots(state).find(l=>l.id==="AS-0919").eta,"2026-09-25");
state.ftReply="rejected";assert.equal(assess(state,"SC6820",100000,"2026-09-25").gap,80000);
assert.equal(assess(state,"SC3215",1000,"2026-09-25").gap,1000,"已分配供给不能再用于新需求");
assert.throws(()=>assess(state,"SC6820",-1,"2026-09-25"));
assert.throws(()=>assess(state,"SC6820",1,"2026-02-30"));
assert.throws(()=>assess(state,"UNKNOWN",1000,"2026-09-25"));
state.shipped=true;assert.equal(tasks(state).find(t=>t.id==="ship").status,"waiting");
state.received=true;assert.equal(tasks(state).find(t=>t.id==="ship").status,"done");
console.log("业务校验通过：供给分配、时间口径、排程影响、确认到期、实际交付与非法输入。");

